/**
 * Category slugs whose synonym key matches a typed query. Matches when a key starts with the query
 * or the query contains the whole key (so "second hand clothes" and "mivum" both work), for queries
 * of 2+ characters. Order: exact key first, then prefix matches, then contained keys; de-duplicated.
 */
export function findSynonymSlugs(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  const exact: string[] = [];
  const prefix: string[] = [];
  const contained: string[] = [];
  for (const [key, slug] of Object.entries(CATEGORY_SYNONYMS)) {
    if (key === q) exact.push(slug);
    else if (key.startsWith(q)) prefix.push(slug);
    else if (q.length >= 4 && q.includes(key) && key.length >= 3) contained.push(slug);
  }
  return Array.from(new Set([...exact, ...prefix, ...contained]));
}
