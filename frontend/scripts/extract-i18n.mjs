#!/usr/bin/env node
// Builds lib/i18n/catalog.generated.ts: every English string in the site that can be translated, so Admin →
// Translations can list them all ("what is still missing?") and export a complete template.
//
//   npm run i18n:extract
//
// It finds (1) tr('…') / <T>…</T> / t('…') calls, (2) plain text between JSX tags, and (3) literal
// placeholder / title / aria-label / alt attributes. Strings written in code are only a starting list: an admin can
// also add any other English text as a new row in the uploaded file, and it is applied by exact match.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SCAN_DIRS = ['app', 'components', 'lib', 'context', 'hooks'];
const SKIP_DIRS = new Set(['node_modules', '.next', '.intlayer', 'admin', 'navtest']);
const SKIP_FILE = /(\.test\.|\.content\.ts|catalog\.generated|[/\\]i18n[/\\]ui\.ts$)/;

function* files(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name)) yield* files(path.join(dir, e.name)); }
    else if (/\.(tsx|ts)$/.test(e.name) && !SKIP_FILE.test(path.join(dir, e.name))) yield path.join(dir, e.name);
  }
}

const unescape = (s) => s.replace(/\\(['"`\\])/g, '$1').replace(/\\n/g, ' ');
const looksLikeText = (s) => {
  const t = s.replace(/\s+/g, ' ').trim();
  if (t.length < 2 || t.length > 200) return false;
  if (!/[A-Za-z]{2}/.test(t)) return false;
  if (/[{}<>=;]|=>|&&|\|\||\$\{|^https?:|^[./@#]|\.(tsx?|jsx?|css|png|svg)\b|^[a-z]+([A-Z][a-z]+)+$/.test(t)) return false; // code-ish
  if (/^[a-z0-9_-]+$/.test(t) && !/\s/.test(t) && t === t.toLowerCase() && t.length < 4) return false;
  return true;
};

const found = new Set();
const add = (s) => { const t = s.replace(/\s+/g, ' ').trim(); if (looksLikeText(t)) found.add(t); };

for (const d of SCAN_DIRS) {
  const abs = path.join(root, d);
  if (!fs.existsSync(abs)) continue;
  for (const f of files(abs)) {
    const src = fs.readFileSync(f, 'utf8');
    for (const m of src.matchAll(/\b(?:tr|t)\(\s*(['"])((?:\\.|(?!\1)[^\\\n])*)\1/g)) add(unescape(m[2]));
    for (const m of src.matchAll(/\btr\(\s*`([^`$]*)`/g)) add(m[1]);
    for (const m of src.matchAll(/<T>\s*([^<{}]+?)\s*<\/T>/g)) add(m[1]);
    if (f.endsWith('.tsx')) {
      for (const m of src.matchAll(/>([^<>{}\n][^<>{}]*)</g)) add(m[1]);
      for (const m of src.matchAll(/\b(?:placeholder|title|aria-label|alt)=(['"])((?:(?!\1)[^\n{}])+)\1/g)) add(m[2]);
    }
  }
}

// Strings that already have a built-in translation are always part of the catalog.
const ui = fs.readFileSync(path.join(root, 'lib/i18n/ui.ts'), 'utf8');
for (const m of ui.matchAll(/^\s*'((?:\\.|[^'\\])+)':\s*e\(/gm)) add(unescape(m[1]));

const list = [...found].sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));
const out = `// GENERATED by scripts/extract-i18n.mjs — do not edit by hand. Run \`npm run i18n:extract\` after adding site text.
// Every English string the site can show that is a candidate for translation (${list.length}).
export const CATALOG: readonly string[] = ${JSON.stringify(list, null, 1)};
`;
fs.writeFileSync(path.join(root, 'lib/i18n/catalog.generated.ts'), out);
console.log(`i18n catalog: ${list.length} strings → lib/i18n/catalog.generated.ts`);
